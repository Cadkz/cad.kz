import assert from 'node:assert/strict'
import { test } from 'node:test'
import { parseRequisites } from '../src/domain/requisites.mjs'

const body = [
  'Товарищество с ограниченной ответственностью "CAD.kz" (КАД.кз),',
  'действующее на основании Устава, в лице директора И. И. Иванова.',
  'БИН 080540017610,',
  '## КБЕ 17',
  'Местонахождение: Республика Казахстан, город Астана, ул. Пушкина, д.6/1',
  'Реквизиты:',
  'Свидетельство о постановке на регистрационный учёт по НДС Серия 62001 № 0022388 от 10.08.2012 г',
  'Дата первичной регистрации: 28 мая 2008 года',
  'Дата последней перерегистрации: 10 июля 2023 года',
  'Банковские реквизиты:',
  '## ИИК KZ248562203140498999',
  'в АО "Банк ЦентрКредит"',
  'БИК KCJBKZKX',
].join('\n\n')

test('реквизиты со старого сайта → вступление и таблица', () => {
  const result = parseRequisites(body)
  assert.ok(result)
  assert.equal(
    result.intro,
    'Товарищество с ограниченной ответственностью «CAD.kz» (КАД.кз), действующее на основании Устава, в лице директора И. И. Иванова.',
  )
  assert.deepEqual(result.fields, [
    { label: 'БИН', value: '080540017610' },
    { label: 'КБЕ', value: '17' },
    { label: 'Местонахождение', value: 'Республика Казахстан, город Астана, ул. Пушкина, д.6/1' },
    {
      label: 'Свидетельство о постановке на регистрационный учёт по НДС',
      value: 'Серия 62001 № 0022388 от 10.08.2012 г',
    },
    { label: 'Дата первичной регистрации', value: '28 мая 2008 года' },
    { label: 'Дата последней перерегистрации', value: '10 июля 2023 года' },
    { label: 'Банковские реквизиты', value: '' },
    { label: 'ИИК', value: 'KZ248562203140498999' },
    { label: 'Банк', value: 'АО «Банк ЦентрКредит»' },
    { label: 'БИК', value: 'KCJBKZKX' },
  ])
})

test('обычный текст — не реквизиты', () => {
  assert.equal(parseRequisites('Просто абзац.\n\nЕщё абзац.'), null)
})
