/** Строки старых характеристик, которые заменяют новые (та же тема другими словами). */
const REPLACED_SPEC = /операцион|^ос(\s|$)|систем.*треб|формат|язык|интерфейс|норм/i

/**
 * Новые характеристики первыми, из прежних — те, что о другом (версия, тип лицензии…).
 * @param {Spec[]} before
 * @param {Spec[]} specs
 * @returns {Spec[]}
 */
export function mergeSpecs(before, specs) {
  return [
    ...specs,
    ...before
      .filter((entry) => !REPLACED_SPEC.test(entry.name.trim()))
      .map(({ name, value }) => ({ name, value })),
  ]
}
