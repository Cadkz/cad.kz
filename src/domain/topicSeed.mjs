/**
 * Первые темы новостей и статей (решение 09.10.2026): у 1135 перенесённых публикаций тем не было,
 * на старом сайте рубрик тоже. Тема ставится по словам в заголовке, потом в анонсе; первое
 * подходящее правило по порядку. Дальше темы правятся в админке.
 */

/** Темы по порядку вывода над списком новостей. */
export const TOPICS = [
  { slug: 'releases', title: 'Релизы и обновления' },
  { slug: 'events', title: 'Вебинары и мероприятия' },
  { slug: 'deals', title: 'Акции и цены' },
  { slug: 'norms', title: 'Нормативы и экспертиза' },
  { slug: 'bim', title: 'BIM и технологии' },
  { slug: 'practice', title: 'Практика и советы' },
  { slug: 'industry', title: 'Новости отрасли' },
]

/** @type {[string, RegExp][]} */
const RULES = [
  [
    'events',
    /вебинар|семинар|конференц|выставк|форум|мероприяти|приглаша|тренинг|award|марафон|мастер-класс|обучени|курс[ауы]?(\s|$)/i,
  ],
  [
    'releases',
    /вышл?[аио]?(\s|$)|выход(\s|$)|выпущен|выпуск|нов(ая|ой|ые|ых) верси|обновлени|обновлен[аоы]? редакци|релиз|верси[яи] \d|что нового|нов(ые|ых) (возможност|функци)|представил|анонс/i,
  ],
  [
    'deals',
    /скидк|(^|[\s«"(])акци[яиюй]|пятниц|выгодн|сниженн|специальн\S* (цен|предлож)|(^|\s)цен[аыуе](\s|$)|подарок|распродаж/i,
  ],
  [
    'norms',
    /СП РК|СНиП|норматив|ценообразован|сборник|экспертиз|закон|постановлени|приказ|ГОСТ|(^|\s)СН РК|стандарт/i,
  ],
  [
    'bim',
    /(^|\s)BIM(\s|$|[-,.])|(^|\s)ИИ(\s|$)|искусствен|облачн|цифров|нейросет|(^|\s)AI(\s|$)|технологи/i,
  ],
  ['practice', /^как |советы|лайфхак|при[её]м|организаци|практик|кейс|опыт|разбираем|ошибк/i],
]

/**
 * Тема публикации (slug). Статьи без совпадений — «Практика и советы», новости — «Новости отрасли».
 * @param {{ kind: string, title: string, excerpt?: string | null }} publication
 * @returns {string}
 */
export function seedTopic({ kind, title, excerpt }) {
  for (const text of [title, excerpt ?? ''])
    for (const [slug, pattern] of RULES) if (pattern.test(text)) return slug
  return kind === 'article' ? 'practice' : 'industry'
}
