/**
 * Правило «на экране один Кадди» (решение владельца 16.10.2026, вечер).
 *
 * Кадди на сайте несколько: в углу экрана (кнопка консультанта), в окне чата и на страницах
 * (баннер «Нашли дешевле», пустая корзина, 404, фильтр без товаров, «Спросить Кадди» рядом
 * с текстом, поиск без результатов). Одновременно виден только один:
 * - окно чата открыто — Кадди только в окне, на странице и в углу его нет;
 * - Кадди страницы в экране — угловой уходит, а из страничных виден один;
 * - иначе — Кадди в углу.
 *
 * pickStageKaddi выбирает, кто из Кадди страницы виден. Порядок visible — сверху вниз по странице.
 * Уже показанный остаётся, пока он в экране (чтобы при прокрутке Кадди не перескакивал),
 * иначе — верхний из видимых.
 *
 * @template T
 * @param {{ chatOpen: boolean, current: T | null, visible: T[] }} state
 * @returns {T | null} Кадди страницы, который показывается; null — на странице никого.
 */
export function pickStageKaddi({ chatOpen, current, visible }) {
  if (chatOpen) return null
  if (current !== null && visible.includes(current)) return current
  return visible[0] ?? null
}
