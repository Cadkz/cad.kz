/**
 * Применить правки к тексту страницы: только те, чей исходный текст в нём есть.
 * @param {string} slug
 * @param {string} body
 */
export function fixPageBody(slug, body) {
  let result = body
  for (const [page, from, to] of PAGE_FIXES)
    if (page === slug && result.includes(from)) result = result.replace(from, to)
  return result
}

