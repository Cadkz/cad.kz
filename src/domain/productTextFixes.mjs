export function applyTextEdits(text) {
  let result = text
  for (const [find, replace] of TEXT_EDITS) result = result.split(find).join(replace)
  return result
}

/**
 * Новое значение поля или null, если трогать нельзя (маркетолог уже поправил).
 * @param {string | null | undefined} current
 * @param {TextChange | undefined} change
 */
export function nextText(current, change) {
  if (!change) return null
  const value = current ?? ''
  if (value === change.to) return null
  if (change.ifEmpty && !value.trim()) return change.to
  if (change.ifHas && value.includes(change.ifHas)) return change.to
  return null
}
