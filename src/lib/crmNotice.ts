/** Состояние передачи заявки, которое видит покупатель: передана, в очереди или демо без CRM. */
export type CrmState = 'sent' | 'queued' | 'demo'

/**
 * Строка под «Заявка сохранена» и «Заказ сохранён» (без рода — подходит обоим). Обещаем связь только когда заявка правда ушла в Битрикс24
 * или стоит в очереди на повтор; в демо без CRM честно говорим, что менеджерам она не уходит.
 */
export function crmDoneText(crm: unknown) {
  if (crm === 'sent') return 'Передано менеджеру — он свяжется с вами в рабочее время.'
  if (crm === 'queued') return 'Менеджер получит данные в ближайшие минуты и свяжется с вами.'
  return 'В демоверсии менеджерам ничего не передаётся.'
}
