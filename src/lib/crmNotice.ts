/** Состояние передачи заявки, которое видит покупатель: передана, в очереди или демо без CRM. */
export type CrmState = 'sent' | 'queued' | 'demo'

/**
 * Строка под «Заявка сохранена». Обещаем связь только когда заявка правда ушла в Битрикс24
 * или стоит в очереди на повтор; в демо без CRM честно говорим, что менеджерам она не уходит.
 */
export function crmDoneText(crm: unknown) {
  if (crm === 'sent') return 'Она передана менеджеру, он свяжется с вами в рабочее время.'
  if (crm === 'queued') return 'Менеджер получит её в ближайшие минуты и свяжется с вами.'
  return 'В демоверсии она не передаётся менеджерам.'
}
